use tonic_build::manual::{Builder, Method, Service};

fn json(name: &str, route: &str, input: &str, output: &str) -> Method {
    Method::builder()
        .name(name)
        .route_name(route)
        .input_type(input)
        .output_type(output)
        .codec_path("crate::codec::JsonCodec")
        .build()
}

