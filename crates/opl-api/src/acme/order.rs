/// HTTP-01 답이 사는 시간
const ANSWER_TTL: i64 = 600;
/// HTTP-01 자기 확인을 다시 해 보는 동안
const PRECHECK_RETRY: Duration = Duration::from_secs(5);
/// 물러서기의 첫 간격과 한도
const BACKOFF_FIRST: i64 = 300;
const BACKOFF_MAX: i64 = 6 * 3600;

/// 실패 `failures`번 뒤 다시 할 때까지(초): 5분 × 2^(n−1), 6시간 한도
pub fn backoff(failures: u32) -> i64 {
    let shift = failures.saturating_sub(1).min(16);
    (BACKOFF_FIRST << shift).min(BACKOFF_MAX)
}

fn now() -> i64 {
    crate::backups::now() as i64
}

/// status를 다시 읽어 고쳐 쓴다(다른 노드의 주문이 같은 인증서를 함께 쓴다 — revision이 바뀌면 다시).
pub async fn modify_status(
    cluster: &Cluster,
    id: Uuid,
    mut change: impl FnMut(&mut CertificateStatus),
) -> Result<(), String> {
    for _ in 0..20 {
        let cert = cluster
            .get::<CertificateSpec>(id)
            .map_err(|e| e.to_string())?
            .ok_or("the certificate was deleted")?;
        let mut status = cert.status.clone();
        change(&mut status);
        if status == cert.status {
            return Ok(());
        }
        match cluster
            .update_status_checked::<CertificateSpec>(id, cert.revision, &status)
            .await
        {
            Ok(_) => return Ok(()),
            Err(opl_cluster::ClusterError::Rejected(
                opl_cluster::types::Rejection::RevisionMismatch { .. },
            )) => {
                tokio::time::sleep(Duration::from_millis(50)).await;
            }
            Err(e) => return Err(e.to_string()),
        }
    }
    Err("the certificate status kept changing".into())
}

/// 계정 키와 등록한 클라이언트. 등록 URL이 없으면 등록하고 status에 적는다.
pub async fn account_client(
    cluster: &Cluster,
    account: &AcmeAccount,
) -> Result<AcmeClient, AcmeError> {
    let spec = &account.spec;
    let url = spec
        .directory_url()
        .ok_or_else(|| AcmeError::Invalid("bad directory".into()))?;
    let key =
        AccountKey::from_pem(spec.key.expose()).map_err(|e| AcmeError::Invalid(e.to_string()))?;
    let mut client = AcmeClient::connect(url, spec.ca_bundle.as_deref(), key).await?;
    match &account.status.url {
        Some(u) => client.set_account(u.clone()),
        None => {
            let eab = spec
                .eab
                .as_ref()
                .map(|e| (e.kid.as_str(), e.hmac_key.expose()));
            let u = client.register(spec.email.as_deref(), eab).await?;
            let mut status = account.status.clone();
            status.url = Some(u);
            status.registered_at = Some(now());
            status.terms = client.directory.meta.terms_of_service.clone();
            status.profiles = client.profiles();
            status.error = None;
            cluster
                .update_status::<AcmeAccountSpec>(account.id, &status)
                .await
                .map_err(|e| AcmeError::Invalid(e.to_string()))?;
        }
    }
    Ok(client)
}

/// 인증서 키 종류의 rcgen 알고리즘
fn key_alg(kind: CertificateKey) -> Result<&'static rcgen::SignatureAlgorithm, AcmeError> {
    match kind {
        CertificateKey::EcdsaP256 => Ok(&rcgen::PKCS_ECDSA_P256_SHA256),
        CertificateKey::EcdsaP384 => Ok(&rcgen::PKCS_ECDSA_P384_SHA384),
        CertificateKey::Rsa2048 => Err(AcmeError::Invalid(
            "rsa2048 keys cannot be generated by this build; use ecdsa-p256 or ecdsa-p384".into(),
        )),
    }
}

/// 노드마다 인증서의 키 파일(받은 인증서의 일련번호마다 하나)
pub fn key_path(dir: &Path, cert: Uuid, serial: &str) -> PathBuf {
    dir.join(format!("{cert}.{serial}.key"))
}

/// `cert`의 키 파일 가운데 `keep`(일련번호)가 아닌 것을 지운다(`keep`이 None이면 모두).
pub fn remove_keys(dir: &Path, cert: Uuid, keep: Option<&str>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    let prefix = format!("{cert}.");
    for e in entries.flatten() {
        let name = e.file_name();
        let Some(name) = name.to_str() else { continue };
        // 일련번호가 이름에 없던 옛 꼴(`{id}.key`)
        if name == format!("{cert}.key") {
            let _ = std::fs::remove_file(e.path());
            continue;
        }
        let Some(serial) = name
            .strip_prefix(&prefix)
            .and_then(|r| r.strip_suffix(".key"))
        else {
            continue;
        };
        if Some(serial) != keep
            && let Err(err) = std::fs::remove_file(e.path())
        {
            tracing::debug!(file = %e.path().display(), error = %err, "cannot remove an old ACME key");
        }
    }
}

fn write_key(path: &Path, pem: &str) -> Result<(), AcmeError> {
    use std::io::Write;
    use std::os::unix::fs::OpenOptionsExt;
    let io =
        |e: std::io::Error| AcmeError::Invalid(format!("cannot write {}: {e}", path.display()));
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).map_err(io)?;
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(dir, std::fs::Permissions::from_mode(0o700));
    }
    let tmp = path.with_extension("tmp");
    let mut f = std::fs::OpenOptions::new()
        .create(true)
        .write(true)
        .truncate(true)
        .mode(0o600)
        .open(&tmp)
        .map_err(io)?;
    f.write_all(pem.as_bytes()).map_err(io)?;
    f.sync_all().map_err(io)?;
    std::fs::rename(&tmp, path).map_err(io)
}

/// CA에 묻기 전 HTTP-01 자기 확인: `http://{이름}/.well-known/acme-challenge/{token}`이 답을 주나
async fn precheck(name: &str, token: &str, expected: &str) -> Result<(), AcmeError> {
    let host = if name.parse::<std::net::Ipv6Addr>().is_ok() {
        format!("[{name}]")
    } else {
        name.to_string()
    };
    let url = format!("http://{host}{}{token}", super::http01::CHALLENGE_PREFIX);
    let client = reqwest::Client::builder()
        .timeout(Duration::from_secs(10))
        .redirect(reqwest::redirect::Policy::limited(3))
        .build()
        .map_err(|e| AcmeError::Http(crate::telemetry::chain(&e)))?;
    let hint = "is port 80 open and http_listen set on every node this name points to? (set precheck: false to skip this check)";
    let response = client.get(&url).send().await.map_err(|e| {
        AcmeError::Invalid(format!(
            "self-check could not reach {url}: {} — {hint}",
            crate::telemetry::chain(&e.without_url())
        ))
    })?;
    let status = response.status();
    let body = response.text().await.unwrap_or_default();
    if !status.is_success() || body.trim() != expected {
        return Err(AcmeError::Invalid(format!(
            "self-check of {url} got HTTP {status} without the challenge answer — {hint}"
        )));
    }
    Ok(())
}

/// HTTP-01 오류에 붙이는 안내
fn hint(e: AcmeError, http01: bool) -> AcmeError {
    match e {
        AcmeError::Connection(d) | AcmeError::Unauthorized(d) | AcmeError::Incorrect(d)
            if http01 =>
        {
            AcmeError::Invalid(format!(
                "the CA could not validate over HTTP-01: {d} — is port 80 open and http_listen set on every node this name points to?"
            ))
        }
        e => e,
    }
}

/// 이번 주문의 대상
struct Target {
    node: Option<Uuid>,
    names: Vec<String>,
    /// 지금 받은 것(갱신이면 `replaces`에 쓴다)
    current: Option<IssuedCert>,
}

fn target(
    cluster: &Cluster,
    cert: &Certificate,
    node: Option<Uuid>,
    here: Uuid,
) -> Result<Target, AcmeError> {
    match (&cert.spec.scope, node) {
        (CertificateScope::Shared, _) => Ok(Target {
            node: None,
            names: cert.spec.names.clone(),
            current: cert.status.shared.clone(),
        }),
        (CertificateScope::PerNode { .. }, Some(n)) if n == here => {
            let me = cluster
                .get::<NodeSpec>(n)
                .ok()
                .flatten()
                .ok_or_else(|| AcmeError::Invalid("this node is not registered".into()))?;
            Ok(Target {
                node: Some(n),
                names: cert.spec.names_for(&me.name, &super::node_address(&me)),
                current: cert.status.nodes.get(&n).cloned(),
            })
        }
        (CertificateScope::PerNode { .. }, _) => Err(AcmeError::Invalid(
            "a per-node certificate is ordered on its node".into(),
        )),
    }
}

/// 도전 하나의 준비(답·TXT)와 치우기
struct Prepared {
    http_tokens: Vec<String>,
    dns: Vec<(Provider, String, Vec<String>, dns::Handle)>,
    challenges: Vec<String>,
}

async fn prepare(
    state: &AppState,
    cert: &Certificate,
    client: &AcmeClient,
    authzs: &[(String, Authorization)],
) -> Result<Prepared, AcmeError> {
    let node: &AcmeNodeConfig = &state.acme;
    let mut out = Prepared {
        http_tokens: Vec::new(),
        dns: Vec::new(),
        challenges: Vec::new(),
    };
    match &cert.spec.challenge {
        ChallengeKind::Http01 => {
            let mut answers = Vec::new();
            for (_, a) in authzs.iter().filter(|(_, a)| a.status != "valid") {
                let c = a
                    .challenges
                    .iter()
                    .find(|c| c.kind == "http-01")
                    .ok_or_else(|| {
                        AcmeError::Invalid(format!(
                            "the CA offers no http-01 challenge for {}",
                            a.identifier.value
                        ))
                    })?;
                answers.push((
                    a.identifier.value.clone(),
                    c.token.clone(),
                    client.key().key_authorization(&c.token),
                    c.url.clone(),
                ));
            }
            let until = now() + ANSWER_TTL;
            let new: Vec<Http01Answer> = answers
                .iter()
                .map(|(_, token, ka, _)| Http01Answer {
                    token: token.clone(),
                    key_authorization: ka.clone(),
                    until,
                })
                .collect();
            modify_status(&state.cluster, cert.id, |s| {
                let t = now();
                s.challenges
                    .retain(|a| a.until > t && !new.iter().any(|n| n.token == a.token));
                s.challenges.extend(new.iter().cloned());
            })
            .await
            .map_err(AcmeError::Invalid)?;
            out.http_tokens = answers.iter().map(|(_, t, _, _)| t.clone()).collect();
            if cert.spec.precheck {
                // 이 노드에는 답이 이미 적용됐지만(쓰기는 이 노드에 적용될 때까지 기다린다) 이름이 가리키는 다른 노드는
                // 아직일 수 있으므로 5초쯤 다시 해 본다. 끝내 안 되면 넣은 답을 치우고 실패한다.
                for (name, token, ka, _) in &answers {
                    let deadline = tokio::time::Instant::now() + PRECHECK_RETRY;
                    loop {
                        match precheck(name, token, ka).await {
                            Ok(()) => break,
                            Err(_) if tokio::time::Instant::now() < deadline => {
                                tokio::time::sleep(Duration::from_millis(500)).await;
                            }
                            Err(e) => {
                                cleanup(state, cert.id, out).await;
                                return Err(e);
                            }
                        }
                    }
                }
            }
            out.challenges = answers.into_iter().map(|(_, _, _, url)| url).collect();
        }
        ChallengeKind::Dns01 { dns: dns_name } => {
            let provider_spec = state
                .cluster
                .get_by_name::<AcmeDnsSpec>(dns_name)
                .map_err(|e| AcmeError::Invalid(e.to_string()))?
                .ok_or_else(|| AcmeError::Invalid(format!("acme-dns {dns_name:?} not found")))?;
            let resolver = node
                .dns_resolver
                .unwrap_or_else(dns::query::system_resolver);
            // TXT 이름마다 값들(와일드카드와 기본 이름이 같은 이름을 쓴다)
            let mut by_name: BTreeMap<String, Vec<String>> = BTreeMap::new();
            for (_, a) in authzs.iter().filter(|(_, a)| a.status != "valid") {
                let c = a
                    .challenges
                    .iter()
                    .find(|c| c.kind == "dns-01")
                    .ok_or_else(|| {
                        AcmeError::Invalid(format!(
                            "the CA offers no dns-01 challenge for {}",
                            a.identifier.value
                        ))
                    })?;
                let name = dns::challenge_name(&a.identifier.value);
                let fqdn = dns::query::follow_cname(resolver, &name).await;
                // CNAME으로 따라간 이름도 스펙 `zones`(있으면) 안이어야 한다 — 다른 영역의 TXT를 건드리지 않게.
                let zones = &provider_spec.spec.zones;
                if fqdn != name && !zones.is_empty() && dns::longest_zone(&fqdn, zones).is_none() {
                    return Err(AcmeError::Invalid(format!(
                        "{name} is a CNAME to {fqdn}, which is outside the zones of acme-dns {dns_name}"
                    )));
                }
                let value = super::jws::dns01_value(&client.key().key_authorization(&c.token));
                by_name.entry(fqdn).or_default().push(value);
                out.challenges.push(c.url.clone());
            }
            for (fqdn, values) in by_name {
                let provider =
                    Provider::new(&provider_spec.spec, node).map_err(AcmeError::Invalid)?;
                let handle = match provider
                    .add(&fqdn, &values, &provider_spec.spec.zones)
                    .await
                {
                    Ok(h) => h,
                    Err(e) => {
                        cleanup(state, cert.id, out).await;
                        return Err(AcmeError::Invalid(format!("DNS provider {dns_name}: {e}")));
                    }
                };
                out.dns
                    .push((provider, fqdn.clone(), values.clone(), handle));
                if let Err(e) = dns::wait_propagated(
                    &provider_spec.spec.propagation,
                    &fqdn,
                    &values,
                    node.dns_resolver,
                )
                .await
                {
                    cleanup(state, cert.id, out).await;
                    return Err(AcmeError::Invalid(e));
                }
            }
        }
    }
    Ok(out)
}

/// 넣은 답·TXT를 치운다(실패는 경고만).
async fn cleanup(state: &AppState, cert: Uuid, prepared: Prepared) {
    if !prepared.http_tokens.is_empty() {
        let tokens = prepared.http_tokens;
        if let Err(e) = modify_status(&state.cluster, cert, |s| {
            s.challenges.retain(|a| !tokens.contains(&a.token));
        })
        .await
        {
            tracing::debug!(error = %e, "cannot remove the HTTP-01 answers");
        }
    }
    for (provider, fqdn, values, handle) in prepared.dns {
        if let Err(e) = provider.remove(&fqdn, &values, &handle).await {
            tracing::warn!(%fqdn, error = %e, "cannot remove the ACME TXT record");
        }
    }
}

/// 주문: 이어 볼 주문이 쓸 만하면 그것, 아니면 새 주문(갱신이면 `replaces`, 거절되면 빼고 한 번 더)
async fn open_order(
    client: &AcmeClient,
    cert: &Certificate,
    target: &Target,
    resume: Option<&String>,
) -> Result<(String, super::client::Order), AcmeError> {
    if let Some(url) = resume
        && let Ok((order, _)) = client.order(url).await
        && matches!(order.status.as_str(), "pending" | "ready")
    {
        return Ok((url.clone(), order));
    }
    let replaces = target
        .current
        .as_ref()
        .and_then(|c| ari::leaf(&c.chain_pem).ok())
        .and_then(|l| l.cert_id);
    let profile = cert.spec.profile.as_deref();
    match client
        .new_order(&target.names, profile, replaces.as_deref())
        .await
    {
        Err(e) if replaces.is_some() && !matches!(e, AcmeError::RateLimited { .. }) => {
            client.new_order(&target.names, profile, None).await
        }
        r => r,
    }
}

async fn issue(
    state: &AppState,
    cert: &Certificate,
    target: &Target,
) -> Result<(IssuedCert, Option<String>), AcmeError> {
    let cluster = &state.cluster;
    let account = cluster
        .get_by_name::<AcmeAccountSpec>(&cert.spec.account)
        .map_err(|e| AcmeError::Invalid(e.to_string()))?
        .ok_or_else(|| {
            AcmeError::Invalid(format!("acme-account {:?} not found", cert.spec.account))
        })?;
    let client = account_client(cluster, &account).await?;
    let key_slot = slot(target.node);
    let (order_url, order) =
        open_order(&client, cert, target, cert.status.orders.get(&key_slot)).await?;
    let url = order_url.clone();
    modify_status(cluster, cert.id, |s| {
        s.orders.insert(key_slot.clone(), url.clone());
    })
    .await
    .map_err(AcmeError::Invalid)?;
    let mut authzs = Vec::new();
    for a in &order.authorizations {
        authzs.push((a.clone(), client.authorization(a).await?.0));
    }
    let http01 = cert.spec.challenge == ChallengeKind::Http01;
    let prepared = prepare(state, cert, &client, &authzs).await?;
    let mut result = Ok(());
    for c in &prepared.challenges {
        if let Err(e) = client.respond(c).await {
            result = Err(e);
            break;
        }
    }
    if result.is_ok() {
        for (url, a) in authzs.iter().filter(|(_, a)| a.status != "valid") {
            if let Err(e) = client.wait_authorization(url, state.acme.poll_limit).await {
                result = Err(AcmeError::Invalid(format!(
                    "{}: {}",
                    a.identifier.value,
                    hint(e, http01)
                )));
                break;
            }
        }
    }
    cleanup(state, cert.id, prepared).await;
    result?;
    // 키와 CSR
    let key = rcgen::KeyPair::generate_for(key_alg(cert.spec.key)?)
        .map_err(|e| AcmeError::Invalid(format!("cannot generate the certificate key: {e}")))?;
    let csr = rcgen::CertificateParams::new(target.names.clone())
        .and_then(|p| p.serialize_request(&key))
        .map_err(|e| AcmeError::Invalid(format!("cannot build the CSR: {e}")))?;
    let cert_url = client
        .finalize(
            &order_url,
            &order.finalize,
            csr.der(),
            state.acme.poll_limit,
        )
        .await?;
    let chain = client
        .certificate(&cert_url, cert.spec.preferred_chain.as_deref())
        .await?;
    let leaf = ari::leaf(&chain).map_err(AcmeError::Invalid)?;
    let ari = match &leaf.cert_id {
        Some(id) => client
            .renewal_info(id)
            .await
            .ok()
            .flatten()
            .map(|w| AriWindow {
                start: w.start,
                end: w.end,
                checked_at: now(),
            }),
        None => None,
    };
    let jitter = if crate::settings::current(cluster)
        .map(|s| s.spec.acme().renew_jitter)
        .unwrap_or(true)
    {
        random_unit()
    } else {
        0.0
    };
    let warning = match cert.spec.renew {
        opl_types::acme::RenewPolicy::DaysBefore { days }
            if !ari::days_before_fits(days, leaf.not_before, leaf.not_after) =>
        {
            Some(format!(
                "renew.days ({days}) is not shorter than this certificate's lifetime ({} days); renewing when a third of it is left",
                (leaf.not_after - leaf.not_before) / 86_400
            ))
        }
        _ => None,
    };
    let issued = IssuedCert {
        serial: leaf.serial,
        not_before: leaf.not_before,
        not_after: leaf.not_after,
        names: target.names.clone(),
        chain_pem: chain,
        ari,
        renew_at: ari::renew_at(
            cert.spec.renew,
            leaf.not_before,
            leaf.not_after,
            ari.as_ref(),
            jitter,
        ),
        key: cert.spec.key,
        error: warning,
        // 창을 받지 못했으면(CA에 ARI가 없음·AKI 없음) 하루 동안 다시 묻지 않는다.
        ari_checked_at: ari.is_none().then(now),
    };
    Ok((issued, Some(key.serialize_pem())))
}

/// 0~1 무작위 수
pub fn random_unit() -> f64 {
    let mut b = [0u8; 4];
    getrandom::fill(&mut b).expect("system random source");
    f64::from(u32::from_be_bytes(b)) / f64::from(u32::MAX)
}

/// Task `acme-order`. 성공하면 받은 인증서(일련번호·만료)를 Task 경고로 남긴다.
pub async fn run(
    state: &AppState,
    certificate: Uuid,
    node: Option<Uuid>,
) -> Result<Option<String>, String> {
    let cluster = &state.cluster;
    let cert = cluster
        .get::<CertificateSpec>(certificate)
        .map_err(|e| e.to_string())?
        .ok_or("the certificate was deleted")?;
    let target = target(cluster, &cert, node, state.node).map_err(|e| e.to_string())?;
    let key_slot = slot(target.node);
    let result = if target.node.is_some() && state.acme.key_dir.is_none() {
        Err(AcmeError::Invalid(
            "this node keeps no ACME keys (no data directory)".into(),
        ))
    } else {
        issue(state, &cert, &target).await
    };
    match result {
        Ok((issued, key_pem)) => {
            let key_pem = key_pem.unwrap_or_default();
            // 노드마다: 키를 먼저 디스크에 — 새 일련번호의 파일이라 지금 끼운 사슬(옛 일련번호)의 키는 그대로다. 끼우는 쪽은
            // status 사슬의 일련번호로 키 파일을 고른다.
            let key_dir = target.node.and(state.acme.key_dir.as_deref());
            if let Some(dir) = key_dir {
                write_key(&key_path(dir, certificate, &issued.serial), &key_pem)
                    .map_err(|e| e.to_string())?;
            }
            let summary = format!(
                "issued serial {} for {} (valid until {})",
                issued.serial,
                issued.names.join(", "),
                super::fmt_time(issued.not_after)
            );
            let shared = target.node.is_none();
            let committed = modify_status(cluster, certificate, |s| {
                match target.node {
                    Some(n) => {
                        s.nodes.insert(n, issued.clone());
                    }
                    None => {
                        s.shared = Some(issued.clone());
                        s.shared_key = Secret::new(key_pem.clone());
                    }
                }
                s.orders.remove(&key_slot);
                s.record_success(target.node);
            })
            .await;
            match (committed, key_dir) {
                (Ok(()), Some(dir)) => remove_keys(dir, certificate, Some(&issued.serial)),
                (Err(e), dir) => {
                    // 적지 못했다: 새 키는 쓸 데가 없다(다음 주문이 새로 받는다).
                    if let Some(dir) = dir {
                        let _ = std::fs::remove_file(key_path(dir, certificate, &issued.serial));
                    }
                    return Err(e);
                }
                _ => {}
            }
            state.audit.record(crate::audit::system_entry(
                "acme.order",
                opl_types::audit::AuditTarget {
                    kind: "certificate".into(),
                    key: cert.name.clone(),
                },
                format!(
                    "acme-order {} issued (serial {}, until {}{})",
                    cert.name,
                    issued.serial,
                    super::fmt_time(issued.not_after),
                    if shared { ", shared" } else { "" }
                ),
            ));
            Ok(Some(summary))
        }
        Err(e) => {
            // 노드마다면 어느 노드의 실패인지 붙인다(요약 `error`·경보 알림에 보인다).
            let message = match target.node {
                Some(n) => {
                    let name = cluster
                        .get::<NodeSpec>(n)
                        .ok()
                        .flatten()
                        .map_or_else(|| n.to_string(), |n| n.name);
                    format!("{name}: {e}")
                }
                None => e.to_string(),
            };
            let wait = e.retry_after().map(|s| s as i64);
            let keep_order = matches!(e, AcmeError::Http(_));
            let failed = modify_status(cluster, certificate, |s| {
                s.record_failure(target.node, message.clone(), now(), |n| {
                    wait.unwrap_or_else(|| backoff(n))
                });
                if !keep_order {
                    s.orders.remove(&key_slot);
                }
            })
            .await;
            if let Err(w) = failed {
                tracing::warn!(error = %w, "cannot record the ACME failure");
            }
            Err(message)
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn backoff_doubles_up_to_six_hours() {
        assert_eq!(backoff(1), 300);
        assert_eq!(backoff(2), 600);
        assert_eq!(backoff(3), 1200);
        assert_eq!(backoff(8), 6 * 3600);
        assert_eq!(backoff(100), 6 * 3600);
        assert_eq!(backoff(0), 300);
    }

    /// 리뷰 1: 새 키는 새 일련번호의 파일이고, 적은 뒤에야 옛 키를 지운다.
    #[test]
    fn key_files_per_serial() {
        let dir = tempfile::TempDir::new().unwrap();
        let (c, other) = (Uuid::from_u128(1), Uuid::from_u128(2));
        write_key(&key_path(dir.path(), c, "aa"), "old").unwrap();
        write_key(&key_path(dir.path(), c, "bb"), "new").unwrap();
        write_key(&key_path(dir.path(), other, "aa"), "x").unwrap();
        assert_eq!(
            std::fs::read_to_string(key_path(dir.path(), c, "aa")).unwrap(),
            "old",
            "writing the new key keeps the installed one"
        );
        remove_keys(dir.path(), c, Some("bb"));
        assert!(!key_path(dir.path(), c, "aa").exists());
        assert!(key_path(dir.path(), c, "bb").exists());
        assert!(key_path(dir.path(), other, "aa").exists());
        remove_keys(dir.path(), other, None);
        assert!(!key_path(dir.path(), other, "aa").exists());
    }
}
